"""Bake the museum's editable Blender gait actions to the native terrain rig.

From the prototype directory:
  blender -b --factory-startup -t 2 --python tools/ground-motion/bake-actions.py
Add ``-- --blend /tmp/ground-actions.blend`` to save an editable Blender scene.
"""

import argparse
import json
import math
import re
import sys
from pathlib import Path

import bpy


DIRECTORY = Path(__file__).resolve().parent
FRAMES = 100
SAMPLES = 32
BODY_TIMES = (0, .22, .50, .76, 1)


def control(collection, name, keys):
    obj = bpy.data.objects.new(name, None)
    obj.rotation_mode = 'XYZ'
    collection.objects.link(obj)
    for phase, location, rotation in keys:
        obj.location = location
        obj.rotation_euler = [math.radians(degrees) for degrees in rotation]
        for path in ('location', 'rotation_euler'):
            obj.keyframe_insert(data_path=path, frame=round(phase * FRAMES))
    action = obj.animation_data.action
    action.name = f'{collection.name} · {name}'
    for layer in action.layers:
        for strip in layer.strips:
            for bag in strip.channelbags:
                for curve in bag.fcurves:
                    for key in curve.keyframe_points:
                        key.handle_left_type = key.handle_right_type = 'AUTO_CLAMPED'
                    curve.update()
    return obj


def create_scene(id, profile):
    collection = bpy.data.collections.new(id)
    bpy.context.scene.collection.children.link(collection)
    body = control(collection, 'Pelvis and shoulders', (
        (t, row[:3], row[3:6]) for t, row in zip(BODY_TIMES, profile['body'], strict=True)
    ))
    accents = control(collection, 'Head pitch and tail yaw', (
        (t, (0, 0, 0), (*row[6:], 0)) for t, row in zip(BODY_TIMES, profile['body'], strict=True)
    ))
    feet = []
    lanes = ('Fore foot', 'Hind foot') if len(profile['swing']) == 2 else ('Hind foot',)
    for lane, keys in zip(lanes, profile['swing'], strict=True):
        full = [(0, 0, 0, 0, 0), *keys, (1, 1, 0, 0, 0)]
        feet.append(control(collection, lane, (
            (t, (progress, height, splay), (pitch, 0, 0)) for t, progress, height, pitch, splay in full
        )))
    return body, accents, feet


def bake(body, accents, feet):
    scene = bpy.context.scene
    scene.frame_start = 0
    scene.frame_end = FRAMES
    body_frames = []
    foot_frames = [[] for _ in feet]
    for index in range(SAMPLES + 1):
        frame = index * FRAMES / SAMPLES
        scene.frame_set(int(frame), subframe=frame % 1)
        body_frames.append([*body.location, *body.rotation_euler, *tuple(accents.rotation_euler)[:2]])
        for foot, rows in zip(feet, foot_frames):
            progress, height, splay = foot.location
            rows.append([progress, height, foot.rotation_euler.x, splay])
    return {'body': body_frames, 'swing': foot_frames}


def js(value):
    if isinstance(value, (int, float)):
        return str(round(value, 5)).rstrip('0').rstrip('.') if round(value, 5) % 1 else str(round(value))
    return json.dumps(value)


def write_motion_file(path, actions):
    lines = ['// Generated by Blender via tools/ground-motion/bake-actions.py.',
             'export const museumGroundActions = {']
    for id, data in actions.items():
        label = id if re.fullmatch(r'[a-z]+', id) else json.dumps(id)
        lines.append(f'  {label}: {{')
        for key in ('period', 'stride', 'duty', 'crouch', 'lift', 'pole'):
            if key in data:
                lines.append(f'    {key}: {js(data[key])},')
        lines.append('    body: [')
        for row in data['body']:
            lines.append('      [' + ', '.join(map(js, row)) + '],')
        lines.append('    ],')
        lines.append('    swing: [')
        for track in data['swing']:
            lines.append('      [')
            for row in track:
                lines.append('        [' + ', '.join(map(js, row)) + '],')
            lines.append('      ],')
        lines.extend(('    ],', '  },'))
    lines.append('};')
    path.write_text('\n'.join(lines) + '\n')


def main():
    args = argparse.ArgumentParser()
    args.add_argument('--blend', type=Path)
    args.add_argument('--output', type=Path, default=DIRECTORY.parents[1] / 'museum' / 'MuseumGroundActions.js')
    settings = args.parse_args(sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else [])
    bpy.ops.wm.read_factory_settings(use_empty=True)
    profiles = {}
    for path in sorted(DIRECTORY.glob('*.json')):
        for id, profile in json.loads(path.read_text()).items():
            if id in profiles:
                raise ValueError(f'Duplicate ground action for {id} in {path.name}')
            if len(profile['lift']) != len(profile['swing']):
                raise ValueError(f'Lift and swing lanes must match for {id}')
            profiles[id] = profile
    actions = {}
    for id, profile in sorted(profiles.items()):
        body, accents, feet = create_scene(id, profile)
        actions[id] = {**profile, **bake(body, accents, feet)}
    write_motion_file(settings.output, actions)
    if settings.blend:
        bpy.ops.wm.save_as_mainfile(filepath=str(settings.blend))
    print(f'Baked {len(actions)} Blender actions to {settings.output}')


if __name__ == '__main__':
    main()
