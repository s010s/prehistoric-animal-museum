"""Bake the existing CC0 forked branch LODs for the vegetation instance batch."""
from base64 import b64encode
import json
import math
from pathlib import Path
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/tidewater/public/models/debris'
NAME = 'dead_quiver_branch_01'
OUTPUT = ROOT / 'creek/WoodlandBranchScan.js'


def accessors(blob):
    size = struct.unpack_from('<I', blob, 12)[0]
    model = json.loads(blob[20:20 + size])
    binary = memoryview(blob)[28 + size:]

    def read(index):
        a = model['accessors'][index]
        view = model['bufferViews'][a['bufferView']]
        code = {5123: 'H', 5125: 'I', 5126: 'f'}[a['componentType']]
        channels = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3}[a['type']]
        offset = view.get('byteOffset', 0) + a.get('byteOffset', 0)
        stride = view.get('byteStride', channels * struct.calcsize(code))
        return [struct.unpack_from('<' + code * channels, binary, offset + i * stride)
                for i in range(a['count'])]

    return model, read


def rotate(p, angle):
    x, y, z = p
    return (x, y * math.cos(angle) + z * math.sin(angle), z * math.cos(angle) - y * math.sin(angle))


def resting_plane(positions):
    def support(angle):
        ys = sorted(rotate(p, angle)[1] for p in positions)
        return .46 * (ys[-1] - ys[0]) + .54 * (ys[len(ys) // 2] - ys[int(len(ys) * .025)])
    return min((i * math.tau / 72 for i in range(72)), key=support)


def prepare():
    model, read = accessors((SOURCE / f'{NAME}.glb').read_bytes())
    colors = Image.open(SOURCE / f'{NAME}_albedo.jpg').convert('RGB').resize((256, 256), Image.Resampling.LANCZOS)
    occlusion = Image.open(SOURCE / f'{NAME}_arm.jpg').convert('RGB').resize((256, 256), Image.Resampling.LANCZOS)
    near = model['meshes'][1]['primitives'][0]
    positions = read(near['attributes']['POSITION'])
    angle = resting_plane(positions)
    ys = sorted(rotate(p, angle)[1] for p in positions)
    contact_y = ys[int(len(ys) * .025)]
    text = ['// Generated by tools/prepare-woodland-branch.py from the vendored Poly Haven',
            '// Dead Quiver Branch 01 (CC0). Each vertex has XYZ millimetres, a signed',
            '// normal, sRGB bark and source occlusion. Indices follow the vertex block.',
            'export const woodlandBranchScan = [']
    for mesh in model['meshes'][1:3]:
        primitive = mesh['primitives'][0]
        pos, norm, tex = (read(primitive['attributes'][name]) for name in ['POSITION', 'NORMAL', 'TEXCOORD_0'])
        indices = [v[0] for v in read(primitive['indices'])]
        packed = bytearray(struct.pack('<HH', len(pos), len(indices)))
        for p, n, uv in zip(pos, norm, tex):
            x, y, z = rotate(p, angle)
            xy = tuple(min(255, int(t % 1 * 256)) for t in uv)
            packed.extend(struct.pack('<hhhbbbBBBB', round(x * 1000), round((y - contact_y) * 1000),
                                      round(z * 1000), *(round(v * 127) for v in rotate(n, angle)),
                                      *colors.getpixel(xy), occlusion.getpixel(xy)[0]))
        packed.extend(struct.pack('<' + 'H' * len(indices), *indices))
        text.append("  '" + b64encode(packed).decode('ascii') + "',")
    OUTPUT.write_text('\n'.join([*text, '];', '']))


if __name__ == '__main__':
    prepare()
